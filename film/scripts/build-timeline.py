#!/usr/bin/env python3
"""Build src/timeline.generated.ts from voice/timings/*.json and voice/placement.json.
Every narration word gets an absolute frame (start, end). Re-run after any voice or placement change."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pl = json.load(open(os.path.join(ROOT, "voice/placement.json")))
fps = pl["fps"]
lines, words = [], []
for lid, start in sorted(pl["starts"].items()):
    t = json.load(open(os.path.join(ROOT, f"voice/timings/{lid}.json")))
    dur = t["words"][-1]["e"]
    lines.append({"id": lid, "text": t["text"], "from": round(start * fps), "to": round((start + dur) * fps), "start": start, "dur": dur})
    for i, w in enumerate(t["words"]):
        clean = re.sub(r"[^\w'’-]", "", w["w"]).lower()
        words.append({"line": lid, "i": i, "w": w["w"], "k": clean, "f0": round((start + w["s"]) * fps), "f1": round((start + w["e"]) * fps)})
total = round(pl["total_seconds"] * fps)
out = ["// GENERATED by scripts/build-timeline.py from voice/timings + voice/placement.json. Do not edit by hand.",
       f"export const FPS = {fps};", f"export const TOTAL = {total};",
       "export type Line = { id: string; text: string; from: number; to: number; start: number; dur: number };",
       "export type Word = { line: string; i: number; w: string; k: string; f0: number; f1: number };",
       "export const LINES: Line[] = " + json.dumps(lines, indent=1) + ";",
       "export const WORDS: Word[] = " + json.dumps(words) + ";"]
open(os.path.join(ROOT, "src/timeline.generated.ts"), "w").write("\n".join(out) + "\n")
for l in lines:
    print(l["id"], l["from"], "-", l["to"], f"({l['start']:.2f}-{l['start']+l['dur']:.2f}s)")
print("words", len(words), "total", total)
