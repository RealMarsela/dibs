#!/usr/bin/env python3
"""Build src/timeline.generated.ts from voice/timings/*.json and voice/placement.json.
Every narration word gets an absolute frame (start, end). Re-run after any voice, placement or variant change.
Variants: L03A (mainnet claim) or L03B (testnet line). Placement starts are written for A; with B every line after
L03 moves by SHIFT frames (difference of the tails' speech end), and TOTAL grows by SHIFT."""
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pl = json.load(open(os.path.join(ROOT, "voice/placement.json")))
fps, variant = pl["fps"], pl.get("variant", "A")
tail = "L03" + variant
ends = {k: pl["starts"][k] + v for k, v in pl["tail_speech_end"].items()}
shift = round((ends[tail] - ends["L03A"]) * fps)
order = ["L01", "L02", "L03", tail, "L04", "L05", "L06", "L07", "L08", "L09"]
lines, words = [], []
for lid in order:
    start = pl["starts"][lid] + (shift / fps if lid >= "L04" else 0)
    t = json.load(open(os.path.join(ROOT, f"voice/timings/{lid}.json")))
    dur = t["words"][-1]["e"]
    lines.append({"id": lid, "text": t["text"], "from": round(start * fps), "to": round((start + dur) * fps), "start": round(start, 3), "dur": dur})
    for i, w in enumerate(t["words"]):
        clean = re.sub(r"[^\w'’.-]", "", w["w"]).lower().rstrip(".")
        words.append({"line": lid, "i": i, "w": w["w"], "k": clean, "f0": round((start + w["s"]) * fps), "f1": round((start + w["e"]) * fps)})
total = round(pl["total_seconds"] * fps) + shift
out = ["// GENERATED by scripts/build-timeline.py from voice/timings + voice/placement.json. Do not edit by hand.",
       f"export const FPS = {fps};", f"export const TOTAL = {total};",
       f'export const VARIANT: "A" | "B" = "{variant}"; // A = mainnet claim (L03A), B = testnet line (L03B)',
       f'export const TAIL = "{tail}"; // the line that ends the pay beat',
       f"export const SHIFT = {shift}; // frames every scene after S03 moves (0 for variant A)",
       "export type Line = { id: string; text: string; from: number; to: number; start: number; dur: number };",
       "export type Word = { line: string; i: number; w: string; k: string; f0: number; f1: number };",
       "export const LINES: Line[] = " + json.dumps(lines, indent=1) + ";",
       "export const WORDS: Word[] = " + json.dumps(words) + ";"]
open(os.path.join(ROOT, "src/timeline.generated.ts"), "w").write("\n".join(out) + "\n")
for l in lines:
    print(l["id"], l["from"], "-", l["to"], f"({l['start']:.2f}s, {l['dur']:.2f}s)")
print("variant", variant, "shift", shift, "total", total, f"({total/fps:.2f}s)")
