#!/usr/bin/env python3
"""Probe public/footage/*.mp4 and write src/footage.generated.ts with the clips that decode (id, size, fps, seconds).
FootageSlot uses ONLY these ids, so a half-written or broken file never reaches a render. Re-run after a clip lands."""
import glob, json, os, subprocess
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ready = {}
for f in sorted(glob.glob(os.path.join(ROOT, "public/footage/*.mp4"))):
    sid = os.path.splitext(os.path.basename(f))[0]
    p = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height,r_frame_rate:format=duration", "-of", "json", f], capture_output=True, text=True)
    try:
        d = json.loads(p.stdout); s = d["streams"][0]; dur = float(d["format"]["duration"])
        tail = subprocess.run(["ffmpeg", "-v", "error", "-ss", str(max(0, dur - 0.5)), "-i", f, "-frames:v", "1", "-f", "null", "-"], capture_output=True, text=True)
        if p.returncode or tail.stderr.strip():
            raise ValueError(tail.stderr.strip()[:120])
        num, den = s["r_frame_rate"].split("/")
        ready[sid] = {"w": s["width"], "h": s["height"], "fps": round(int(num) / int(den), 3), "seconds": round(dur, 3)}
        print("ready ", sid, ready[sid])
    except Exception as e:
        print("SKIP  ", sid, "(does not decode:", str(e)[:100] or p.stderr.strip()[:100], ")")
out = "// GENERATED by scripts/footage-ready.py. Only clips listed here are used by FootageSlot.\n"
out += "export const FOOTAGE_READY: Record<string, { w: number; h: number; fps: number; seconds: number }> = " + json.dumps(ready, indent=1) + ";\n"
open(os.path.join(ROOT, "src/footage.generated.ts"), "w").write(out)
